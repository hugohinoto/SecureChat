const ALL_TEXT_ALIASES = { ...TEXT_ALIASES.en, ...DYNAMIC_ALIASES };
const REVERSE_TEXT_ALIASES = new Map(Object.entries(ALL_TEXT_ALIASES).map(([ja, en]) => [en, ja]));
const JAPANESE_TEXT_PARTS = Object.entries(ALL_TEXT_ALIASES)
  .filter(([japanese]) => japanese.length >= 5)
  .sort((a, b) => b[0].length - a[0].length);
const ENGLISH_TEXT_PARTS = [...REVERSE_TEXT_ALIASES.entries()]
  .filter(([english]) => english.length >= 5)
  .sort((a, b) => b[0].length - a[0].length);

export function translateText(value, locale = getLocale()) {
  if (typeof value !== "string") return value;

  // Exact Japanese source aliases should be translated before attempting to
  // normalize an already-localized DOM value. This avoids matching short Japanese
  // words inside longer Japanese phrases during reverse-fragment processing.
  const directLocaleAliases = {
    ...(TEXT_ALIASES[locale] || {}),
    ...(LOCALIZED_DYNAMIC_ALIASES[locale] || {})
  };
  if (locale !== "ja" && Object.hasOwn(directLocaleAliases, value)) {
    return directLocaleAliases[value];
  }

  // DOM text may already have been translated during an earlier locale change.
  // Normalize known localized aliases back to their Japanese source before applying
  // the newly selected locale, so switching languages is reversible.
  let source = value;
  const reverseLocaleAliases = new Map();
  for (const aliases of [...Object.values(TEXT_ALIASES), ...Object.values(LOCALIZED_DYNAMIC_ALIASES)]) {
    for (const [japanese, localized] of Object.entries(aliases)) {
      reverseLocaleAliases.set(localized, japanese);
    }
  }
  for (const [key, japanese] of Object.entries(translations.ja)) {
    for (const dictionary of Object.values(translations)) {
      if (dictionary[key]) reverseLocaleAliases.set(dictionary[key], japanese);
    }
  }
  if (reverseLocaleAliases.has(source)) {
    source = reverseLocaleAliases.get(source);
  } else {
    // Also reverse translated fragments in composed messages that include
    // dynamic values such as server details, timestamps, or counts.
    const reverseLocaleParts = [...reverseLocaleAliases.entries()]
      .filter(([, japanese]) => japanese.length >= 5 || /^\s/.test(japanese) || /\s$/.test(japanese))
      .sort((a, b) => b[0].length - a[0].length);
    for (const [localized, japanese] of reverseLocaleParts) {
      source = source.split(localized).join(japanese);
    }
    for (const [key, localized] of Object.entries(translations[locale] || {})) {
      if (source === localized && translations.ja[key]) {
        source = translations.ja[key];
        break;
      }
    }
  }
  if (REVERSE_TEXT_ALIASES.has(source)) {
    source = REVERSE_TEXT_ALIASES.get(source);
  } else {
    for (const [english, japanese] of ENGLISH_TEXT_PARTS) {
      source = source.split(english).join(japanese);
    }
  }

  if (locale === "ja") return source;

  const localeAliases = { ...(TEXT_ALIASES[locale] || {}), ...(LOCALIZED_DYNAMIC_ALIASES[locale] || {}) };
  if (Object.hasOwn(localeAliases, source)) return localeAliases[source];

  // Translate known Japanese source strings through the locale's keyed dictionary.
  for (const [key, japanese] of Object.entries(translations.ja)) {
    if (source === japanese) {
      return translations[locale]?.[key]
        ?? (locale === "en" ? translations.en?.[key] : japanese)
        ?? japanese;
    }
  }

  if (locale === "en") {
    if (Object.hasOwn(TEXT_ALIASES.en, source)) return TEXT_ALIASES.en[source];
    let translated = source;
    for (const [japanese, english] of JAPANESE_TEXT_PARTS) {
      translated = translated.split(japanese).join(english);
    }
    return translated;
  }

  // Apply locale-specific fragments to composed dynamic messages (for example,
  // a translated label followed by a changing timestamp or count).
  const localizedParts = Object.entries(localeAliases)
    .filter(([japanese]) => japanese.length >= 5 || /^\s/.test(japanese) || /\s$/.test(japanese))
    .sort((a, b) => b[0].length - a[0].length);
  let localized = source;
  for (const [japanese, translated] of localizedParts) {
    localized = localized.split(japanese).join(translated);
  }
  // Never fall back to English for partially covered strings.
  return localized;
}

function applyTextAliases(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    if (node.parentElement?.closest?.("[data-user-content]")) continue;
    const replacement = translateText(node.textContent);
    if (replacement !== node.textContent) node.textContent = replacement;
  }
  root.querySelectorAll?.("[placeholder],[aria-label],[title],[data-i18n-placeholder],[data-i18n-aria-label],[data-i18n-title]").forEach(element => {
    for (const attribute of ["placeholder","aria-label","title"]) {
      const value = element.getAttribute(attribute);
      if (!value) continue;
      const translated = translateText(value);
      if (translated !== value) element.setAttribute(attribute, translated);
    }
  });
}

export function applyTranslations(root = document) {
  const locale = getLocale();
  document.documentElement.lang = locale;
  root.querySelectorAll("[data-i18n]").forEach(element => {
    element.textContent = t(element.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
    element.placeholder = t(element.dataset.i18nPlaceholder);
  });
  root.querySelectorAll("[data-i18n-aria-label]").forEach(element => {
    element.setAttribute("aria-label", t(element.dataset.i18nAriaLabel));
  });
  root.querySelectorAll("[data-i18n-title]").forEach(element => {
    element.title = t(element.dataset.i18nTitle);
  });
  root.querySelectorAll("meta[data-i18n-content]").forEach(element => {
    element.content = t(element.dataset.i18nContent);
  });
  applyTextAliases(root);
}

export function initI18n({ observe = true } = {}) {
  const locale = getLocale();
  document.documentElement.lang = locale;
  applyTranslations(document);
  document.querySelectorAll("[data-language-selector]").forEach(select => {
    select.value = locale;
    select.setAttribute("aria-label", t("language"));
    select.addEventListener("change", () => setLocale(select.value));
  });
  if (observe && typeof MutationObserver !== "undefined") {
    let scheduled = false;
    const observer = new MutationObserver(() => {
      if (scheduled) return;
      scheduled = true;
      queueMicrotask(() => {
        scheduled = false;
        applyTextAliases(document);
      });
    });
    // Attribute writes are deliberately excluded: applyTextAliases updates attributes
    // itself, so observing them would create a MutationObserver feedback loop.
    observer.observe(document.documentElement, { childList:true, characterData:true, subtree:true });
  }
  return locale;
}
