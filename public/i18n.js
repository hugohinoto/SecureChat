export function getLocale() {
  try {
    const saved = localStorage.getItem(I18N_STORAGE_KEY);
    if (SUPPORTED_LOCALES.includes(saved)) return saved;
  } catch {}
  return "ja";
}

export function setLocale(locale) {
  const next = SUPPORTED_LOCALES.includes(locale) ? locale : "ja";
  try { localStorage.setItem(I18N_STORAGE_KEY, next); } catch {}
  document.documentElement.lang = next;
  document.querySelectorAll("[data-language-selector]").forEach(select => {
    select.value = next;
  });
  applyTranslations(document);
  document.dispatchEvent(new CustomEvent("securechat:localechange", { detail:{ locale:next } }));
  return next;
}

export function t(key, variables = {}) {
  const locale = getLocale();
  // English is the only locale that falls back to English. In partially translated
  // locales, keep the original Japanese instead of silently mixing in English.
  let value = translations[locale]?.[key]
    ?? (locale === "en" ? translations.en?.[key] : translations.ja?.[key])
    ?? key;
  for (const [name, replacement] of Object.entries(variables)) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}

